const HI_DIGITS = ["०", "१", "२", "३", "४", "५", "६", "७", "८", "९"];

export function localizeDigits(text: string | number | null | undefined, lang: string) {
  if (lang !== "hi" || text == null) return text;
  return String(text).replace(/[0-9]/g, (d: string) => HI_DIGITS[+d] ?? d);
}

